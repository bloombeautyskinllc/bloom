/**
 * Builds SQL to paste into Supabase > SQL Editor (one transaction), for projects managed without the CLI.
 *
 *   node scripts/build-full-setup.mjs                  -> supabase/full-setup.generated.sql (fresh project: all migrations + seed)
 *   node scripts/build-full-setup.mjs --after <version> -> supabase/update-<version>.generated.sql (only newer migrations)
 *
 * Both record the applied migrations so `supabase db push` later only applies newer ones.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..', 'supabase');
const afterIndex = process.argv.indexOf('--after');
const after = afterIndex > -1 ? process.argv[afterIndex + 1] : null;
if (afterIndex > -1 && !/^\d{14}$/.test(after ?? '')) {
  console.error('--after needs a 14-digit migration version, e.g. 20260930000100');
  process.exit(1);
}

const migrations = readdirSync(join(root, 'migrations'))
  .filter((f) => f.endsWith('.sql'))
  .sort()
  .filter((f) => !after || f.slice(0, 14) > after);
if (migrations.length === 0) {
  console.log(`No migrations after ${after}.`);
  process.exit(0);
}

const parts = [
  '-- =============================================================================',
  `-- BLOOM Beauty Skin: ${after ? `database update (migrations after ${after})` : 'full database setup'} (GENERATED by scripts/build-full-setup.mjs)`,
  `-- ${after ? 'Run once on a project that already has everything up to that version.' : 'Run once on a FRESH Supabase project.'}`,
  '-- SQL Editor > New query > paste > Run. One transaction: if anything fails, nothing is applied.',
  '-- =============================================================================',
  '',
  'begin;',
  '',
];

for (const file of migrations) {
  parts.push(`-- >>> migration ${file}`, readFileSync(join(root, 'migrations', file), 'utf8').trim(), '');
}
if (!after) {
  parts.push('-- >>> seed.sql (catalog, business hours, specialist, settings)', readFileSync(join(root, 'seed.sql'), 'utf8').trim(), '');
}

parts.push(
  '-- >>> migration history for the Supabase CLI',
  'create schema if not exists supabase_migrations;',
  'create table if not exists supabase_migrations.schema_migrations (version text primary key, statements text[], name text);',
  'insert into supabase_migrations.schema_migrations (version, name) values',
  migrations
    .map((f) => {
      const [version, ...name] = f.replace(/\.sql$/, '').split('_');
      return `  ('${version}', '${name.join('_')}')`;
    })
    .join(',\n'),
  'on conflict (version) do nothing;',
  '',
);

const extraFile = process.argv.includes('--with-fixes') ? join(root, 'fixes.sql') : null;
if (extraFile) parts.push('-- >>> one-off fixes', readFileSync(extraFile, 'utf8').trim(), '');

parts.push('commit;', '');

const out = join(root, after ? `update-${after}.generated.sql` : 'full-setup.generated.sql');
writeFileSync(out, parts.join('\n'));
console.log(`Wrote ${out}: ${migrations.length} migration(s)${after ? '' : ' + seed'}`);
